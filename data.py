def all_exercises():
    out = []
    for day, w in WORKOUTS.items():
        for ex in w["exercises"]:
            out.append((day, ex))
    return out


def get_exercise(eid: str):
    for day, w in WORKOUTS.items():
        for ex in w["exercises"]:
            if ex["id"] == eid:
                return day, ex
    return None, None


def format_workout(key: str) -> str:
    w = WORKOUTS[key]
    lines = [
        f"<b>{w['title']}</b>",
        f"Цель: {w['goal']}",
        f"Порядок: {w['sequence']}",
        "",
        f"<i>Разминка:</i> {w['warmup']}",
        "",
    ]
    for i, ex in enumerate(w["exercises"], 1):
        lines.append(f"<b>{i}. {ex['name']}</b> — {ex['reps']}")
        lines.append(ex["cue"])
        lines.append("")
    if w.get("note"):
        lines.append(w["note"])
    lines.append("Каждое упражнение — все подходы, затем следующее.")
    return "\n".join(lines).strip()


def format_subs(key: str) -> str:
    w = WORKOUTS[key]
    lines = [f"<b>Замены · {w['title']}</b>", "Если нет снаряда, болит сустав или очередь — бери альтернативу.", ""]
    for i, ex in enumerate(w["exercises"], 1):
        alts = " / ".join(ex["alts"])
        lines.append(f"{i}. {ex['name']}")
        lines.append(f"   → {alts}")
    return "\n".join(lines)


def cycle_info(start_iso: str | None, length: int | None, today: date | None = None) -> str:
    if not start_iso:
        return "Цикл не задан. Нажми «Начало цикла» и пришли дату, например 28.08.2026."
    try:
        start = date.fromisoformat(start_iso)
    except ValueError:
        return "Дата цикла записана криво. Задай заново."
    length = length or 28
    length = max(21, min(40, int(length)))
    today = today or date.today()
    day_num = (today - start).days % length + 1
    if day_num <= 5:
        phase = "менструация"
        train = (
            "Силовые можно, но без героизма. Если тянет низ или голова — "
            "снизь вес на 10–20%, ноги не в отказ, кардио спокойное."
        )
    elif day_num <= 13:
        phase = "фолликулярная"
        train = (
            "Обычно лучше переносится прогрессия и база. "
            "Хорошее окно для силовых и новых рабочих весов."
        )
    elif day_num <= 16:
        phase = "овуляторная"
        train = (
            "Сила часто на пике, но связки эластичнее. "
            "Техника жёстче, без грязных ПР в рывковых движениях."
        )
    else:
        phase = "лютеиновая"
        train = (
            "Может тяжелее даваться объём и жара. "
            "Чуть больше углеводов, сон, не стыдно убрать 1 подход. "
            "ПМС ≠ лень — это физиология."
        )
    return (
        f"<b>Цикл · день {day_num} из {length}</b>\n"
        f"Фаза: {phase}\n"
        f"Старт последних месячных: {start.strftime('%d.%m.%Y')}\n\n"
        f"{train}\n\n"
        f"{CYCLE_HELP}"
    )


def calc_kbju(weight: float, height: float, age: int, sex: str, activity: str, goal: str) -> str:
    if sex == "m":
        bmr = 10 * weight + 6.25 * height - 5 * age + 5
    else:
        bmr = 10 * weight + 6.25 * height - 5 * age - 161
    mult = {"low": 1.2, "mid": 1.375, "high": 1.55, "sport": 1.725}[activity]
    tdee = bmr * mult
    if goal == "cut":
        kcal = tdee - 350
    elif goal == "bulk":
        kcal = tdee + 300
    else:
        kcal = tdee
    protein = 1.8 * weight
    fat = 1.0 * weight
    carbs = max((kcal - protein * 4 - fat * 9) / 4, 80)
    goal_name = {"cut": "сушка", "bulk": "набор", "keep": "поддержание"}[goal]
    act_name = {
        "low": "сидячий",
        "mid": "лёгкая активность",
        "high": "тренировки 3–5×",
        "sport": "тяжёлые тренировки",
    }[activity]
    return (
        f"<b>Расчёт под тебя</b>\n"
        f"Пол: {'муж' if sex == 'm' else 'жен'}, {age} лет, {weight} кг, {height} см\n"
        f"Активность: {act_name}\n"
        f"Цель: {goal_name}\n\n"
        f"BMR ≈ {int(bmr)} ккал\n"
        f"Поддержка (TDEE) ≈ {int(tdee)} ккал\n"
        f"<b>Цель по калориям: {int(kcal)} ккал</b>\n\n"
        f"Белок: {int(protein)} г\n"
        f"Жиры: {int(fat)} г\n"
        f"Углеводы: {int(carbs)} г\n\n"
        f"Это ориентир. Если вес стоит 2–3 недели — сдвинь калории на 150–200."
    )
